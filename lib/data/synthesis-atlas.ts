const mechanism = (
  id: SynthesisAtlasMechanism["id"],
  title: SynthesisAtlasLocalizedText,
  nucleophile: SynthesisAtlasLocalizedText,
  electrophile: SynthesisAtlasLocalizedText,
  intermediate: SynthesisAtlasLocalizedText,
  stereochemicalOutcome: SynthesisAtlasLocalizedText,
  commonError: SynthesisAtlasLocalizedText,
  moves: readonly [
    readonly [SynthesisAtlasLocalizedText, SynthesisAtlasLocalizedText, SynthesisAtlasLocalizedText],
    ...readonly (readonly [SynthesisAtlasLocalizedText, SynthesisAtlasLocalizedText, SynthesisAtlasLocalizedText])[],
  ],
  anchors?: readonly Readonly<{
    from: SynthesisAtlasMechanism["electronMoves"][number]["fromAnchor"];
    to: SynthesisAtlasMechanism["electronMoves"][number]["toAnchor"];
  }>[],
): SynthesisAtlasMechanism => ({
  id,
  evidenceState: "source-context",
  title,
  nucleophile,
  electrophile,
  intermediate,
  stereochemicalOutcome,
  commonError,
  electronMoves: moves.map(([from, to, explanation], index) => {
    const anchor = anchors?.[index];
    return {
      id: `${id}:move-${index + 1}`,
      from,
      to,
      explanation,
      ...(anchor?.from && anchor.to
        ? { fromAnchor: anchor.from, toAnchor: anchor.to }
        : {}),
    };
  }),
});

